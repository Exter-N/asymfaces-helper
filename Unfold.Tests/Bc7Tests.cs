    public void TestMirror(int mode, ulong originalL, ulong originalU, ulong expectedL, ulong expectedU)
    {
        if (BitOperations.TrailingZeroCount(originalL) != mode || BitOperations.TrailingZeroCount(expectedL) != mode)
            Assert.Inconclusive();

        var block = new Bc7Block(originalL, originalU);
        Console.WriteLine($"Original: {block} ({block.Lower:X16} {block.Upper:X16})");
        block.Mirror();
        Console.WriteLine($"Mirrored: {block} ({block.Lower:X16} {block.Upper:X16})");
        Assert.That(block, Is.EqualTo(new Bc7Block(expectedL, expectedU)));
    }

